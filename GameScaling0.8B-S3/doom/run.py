"""Bounded Battle-1 reproduction: original prompt; local MLX/ViZDoom adapter.

This is not an exact reproduction of the paper's engine/executor or a claim
about its score. The engine advances during inference in realtime mode.
"""
import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import hashlib
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import io
import json
import os
from pathlib import Path
import sys
import threading
import time

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
os.environ['ANO_GAMESCALING_PROMPT_PROFILE']='doom'
from install_assets import install


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--max-decisions',type=int,default=10)
    parser.add_argument('--mode',choices=('realtime','paused'),default='realtime')
    parser.add_argument('--seed',type=int,default=123)
    parser.add_argument('--viewer-port',type=int,default=8769)
    args=parser.parse_args()
    if not 1<=args.max_decisions<=1000:parser.error('Use 1–1000 decisions')
    out=args.output.expanduser().resolve();out.mkdir(parents=True,exist_ok=True)
    if (out/'config.json').exists():parser.error('Choose a new output directory for each run')
    assets=install()
    import vizdoom as v
    from PIL import Image
    from webrtc_live import NativePolicy,SYSTEM,MODEL_SPEC,PRECISION
    from gamescaling import PolicyConfig
    from gamescaling.policy import encode_image
    from control_adapter import BUTTONS,CHUNK_TICS,packet_vector
    public={'status':'loading model','mode':args.mode,'model':MODEL_SPEC.name}
    images={'frame':b'', 'input':b''}
    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            # Bind and Host checks both keep this diagnostics-only viewer local.
            if self.headers.get('Host') not in (f'127.0.0.1:{args.viewer_port}',f'localhost:{args.viewer_port}'):
                self.send_error(403);return
            if self.path=='/live':
                data=(Path(__file__).parent/'viewer.html').read_bytes();mime='text/html'
            elif self.path=='/state':data=json.dumps(public.copy()).encode();mime='application/json'
            elif self.path in ('/frame','/input'):data=images[self.path[1:]];mime='image/jpeg'
            else:self.send_error(404);return
            self.send_response(200);self.send_header('Content-Type',mime)
            self.send_header('Cache-Control','no-store');self.send_header('Content-Length',str(len(data)))
            self.end_headers();self.wfile.write(data)
        def log_message(self,*args):pass
    server=ThreadingHTTPServer(('127.0.0.1',args.viewer_port),Handler)
    threading.Thread(target=server.serve_forever,daemon=True).start()
    print(f'Doom live viewer: http://127.0.0.1:{args.viewer_port}/live',flush=True)
    def record(row):
        with (out/'events.jsonl').open('a') as stream:stream.write(json.dumps({'wall_time':time.time(),**row})+'\n')
    def jpeg(image):
        buffer=io.BytesIO();image.save(buffer,format='JPEG',quality=85);return buffer.getvalue()
    game=v.DoomGame();pool=ThreadPoolExecutor(max_workers=1,thread_name_prefix='doom-model-owner')
    future=None;count=0;reason='episode_end'
    try:
        policy=pool.submit(NativePolicy).result()
        config={'model':MODEL_SPEC.name,'revision':MODEL_SPEC.revision,'precision':PRECISION,
            'parameter_dtypes':policy.parameter_dtypes,'seed':args.seed,'mode':args.mode,
            'max_decisions':args.max_decisions,'wall_cap_seconds':180,'engine_hz':35,
            'image_size':[1280,720],'history_limit':5,'temperature':1.0,'max_tokens':2048,
            'input_image_encoding':'upstream JPEG quality 90 decoded before MLX image processor',
            'prompt_sha256':hashlib.sha256(SYSTEM.encode()).hexdigest(),
            'vizdoom_version':v.__version__,'scenario_commit':__import__('install_assets').COMMIT,
            'differences':['MLX FP16 versus publisher BF16/vLLM runtime',
                'ViZDoom 1.3.2 with bundled Freedoom; original artwork/version not established',
                'Authors did not publish executor: local FOV-based mouse mapping and 35Hz tic adapter',
                '1280x720 RGB, HUD on, skill 1, 35 startup tics, scenario timeout 2100 tics',
                'Separate-image feature reuse can change floating-point rounding',
                'Doom runner waits for each action chunk before starting the next inference; WebRTC overlaps them']}
        (out/'config.json').write_text(json.dumps(config,indent=2)+'\n')
        (out/'system-prompt.txt').write_text(SYSTEM+'\n')
        # Logs/demos generated by the engine also remain in the selected run directory.
        os.chdir(out)
        game.load_config(str(assets/'D3_battle.cfg'))
        game.set_doom_scenario_path(str(assets/'D3_battle.wad'))
        game.set_doom_game_path(str(Path(v.install_path)/'freedoom2.wad'))
        game.set_doom_skill(1);game.set_seed(args.seed)
        game.set_screen_resolution(v.ScreenResolution.RES_1280X720);game.set_screen_format(v.ScreenFormat.RGB24)
        game.set_render_hud(True);game.set_window_visible(False);game.set_sound_enabled(False)
        game.set_mode(v.Mode.PLAYER);game.set_available_buttons(BUTTONS)
        game.set_episode_start_time(0);game.add_game_args('+fov 90');game.init()
        game.new_episode('episode.lmp');game.make_action([0.0]*len(BUTTONS),35)
        identity=('doom',str(out),0,0);cfg=PolicyConfig();packet=None;packet_tic=0;turn=None
        started=time.monotonic();deadline=started;tick=0
        def screenshot():
            state=game.get_state()
            return Image.fromarray(state.screen_buffer.copy()) if state else None
        while not game.is_episode_finished() and not game.is_player_dead():
            now=time.monotonic()
            if now-started>180:reason='wall_cap';break
            image=screenshot()
            if image is None:break
            if tick%4==0:images['frame']=jpeg(image)
            if future is None and packet is None:
                if count>=args.max_decisions:reason='decision_cap';break
                # The upstream client sends quality-90 JPEG. Decode that exact image for MLX.
                encoded=base64.b64decode(encode_image(image,cfg).split(',',1)[1])
                model_image=Image.open(io.BytesIO(encoded)).convert('RGB')
                model_image.save(out/f'input-{count+1:04}.png');images['input']=jpeg(model_image)
                input_tick=game.get_episode_time();public.update(status='inferring',decisions=count)
                future=pool.submit(policy.infer,model_image,identity,'',[.5,.5],observation_text='current game screen')
            if future is not None and future.done():
                packet,timing,turn=future.result();future=None;count+=1;packet_tic=0
                record({'kind':'decision','decision':count,'input_tick':input_tick,
                    'result_tick':game.get_episode_time(),'parsed':packet.parsed,
                    'mouse':packet.mouse,'steps':packet.steps,'timing':timing})
                public.update(status='acting',decisions=count,inference_ms=timing['inference_ms'],
                    images_in_context=timing['images_in_context'],text=timing['reasoning'],parsed=packet.parsed)
            if packet is not None or args.mode=='realtime':
                vector,unsupported=packet_vector(packet,packet_tic) if packet else ([0.0]*len(BUTTONS),[])
                game.make_action(vector,1);tick+=1
                if packet is not None:
                    record({'kind':'engine_action','decision':count,'tic':packet_tic,'requested':vector,
                        'engine_last_action':list(game.get_last_action()),'unsupported':unsupported})
                    packet_tic+=1
                    if packet_tic==CHUNK_TICS:
                        policy.remember(identity,turn,True);packet=None
                deadline+=1/35
                if deadline<time.monotonic()-.1:deadline=time.monotonic()
                time.sleep(max(0,deadline-time.monotonic()))
            else:
                # Paused mode is diagnostic only: no engine progress while inference is pending.
                deadline=time.monotonic();time.sleep(.005)
            public.update(game_time_s=game.get_episode_time()/35)
        wall=time.monotonic()-started
        summary={'reason':reason,'decisions':count,'game_tics':game.get_episode_time(),
            'wall_seconds':wall,'engine_advance_hz':(game.get_episode_time()-35)/wall,
            'kills':game.get_game_variable(v.GameVariable.KILLCOUNT),
            'health':game.get_game_variable(v.GameVariable.HEALTH),'mode':args.mode}
        (out/'summary.json').write_text(json.dumps(summary,indent=2)+'\n');public.update(summary,status='finished')
        print(json.dumps(summary),flush=True)
    finally:
        # Native model work is never interrupted half-way through a GPU call.
        pool.shutdown(wait=True,cancel_futures=True)
        game.close();server.shutdown();server.server_close()


if __name__=='__main__':main()
